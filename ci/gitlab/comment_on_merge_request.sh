#!/usr/bin/env bash
# Auto Architecture Diagram - GitLab merge request commenter
#
# Posts (or updates) a sticky note on the current merge request with the
# generated architecture Markdown. Best-effort: missing token or API errors are
# reported as warnings so the pipeline is never blocked by comment failures.
set -euo pipefail

log()  { printf '\033[0;34m[auto-arch-diagram]\033[0m %s\n' "$*"; }
warn() { printf '\033[0;33m[auto-arch-diagram] WARNING:\033[0m %s\n' "$*" >&2; }

TOKEN="${AUTO_ARCH_GITLAB_TOKEN:-}"
if [ -z "${TOKEN}" ]; then
  warn "AUTO_ARCH_GITLAB_TOKEN is not set - skipping merge request comment."
  warn "Create a masked project/group variable with 'api' scope to enable comments."
  exit 0
fi

if [ -z "${CI_MERGE_REQUEST_IID:-}" ]; then
  log "Not a merge request pipeline - skipping merge request comment."
  exit 0
fi

if [ "${AUTO_ARCH_HAS_CHANGES:-}" != "true" ]; then
  log "No IaC changes in this pipeline - skipping merge request comment."
  exit 0
fi

OUT_DIR="${AUTO_ARCH_OUT_DIR:-artifacts}"
comment_file="${AUTO_ARCH_COMMENT_FILE:-}"
if [ -z "${comment_file}" ]; then
  if [ -f "${OUT_DIR}/architecture-diagram.md" ]; then
    comment_file="${OUT_DIR}/architecture-diagram.md"
  else
    comment_file="${OUT_DIR}/gitlab-ci-summary.md"
  fi
fi

if [ ! -f "${comment_file}" ]; then
  warn "Comment body file not found: ${comment_file} - skipping comment."
  exit 0
fi

log "Publishing diagram note on merge request !${CI_MERGE_REQUEST_IID}"
AUTO_ARCH_COMMENT_FILE="${comment_file}" python3 - <<'PY'
import json
import os
import sys
import urllib.error
import urllib.parse
import urllib.request

api = os.environ.get("CI_API_V4_URL", "").rstrip("/")
project_id = os.environ.get("CI_PROJECT_ID", "")
mr_iid = os.environ.get("CI_MERGE_REQUEST_IID", "")
token = os.environ.get("AUTO_ARCH_GITLAB_TOKEN", "")
comment_file = os.environ["AUTO_ARCH_COMMENT_FILE"]
pipeline_url = os.environ.get("CI_PIPELINE_URL", "")
job_url = os.environ.get("CI_JOB_URL", "")

MARKER = "<!-- auto-arch-diagram -->"
MAX_CHARS = 200_000

def warn(message):
    print(f"[auto-arch-diagram] WARNING: {message}", file=sys.stderr)

def request(method, path, payload=None, params=None):
    url = f"{api}/projects/{urllib.parse.quote(str(project_id), safe='')}{path}"
    if params:
        url += "?" + urllib.parse.urlencode(params)
    data = json.dumps(payload).encode("utf-8") if payload is not None else None
    req = urllib.request.Request(url, data=data, method=method)
    req.add_header("PRIVATE-TOKEN", token)
    if data is not None:
        req.add_header("Content-Type", "application/json")
    with urllib.request.urlopen(req, timeout=30) as response:
        body = response.read().decode("utf-8")
        return json.loads(body) if body else None

with open(comment_file, encoding="utf-8") as handle:
    markdown = handle.read().strip()

if not markdown:
    warn("Comment body is empty - skipping comment.")
    raise SystemExit(0)

links = []
if pipeline_url:
    links.append(f"[View pipeline]({pipeline_url})")
if job_url:
    links.append(f"[Job artifacts]({job_url})")

body = MARKER + "\n## \U0001F3D7 Architecture diagram\n\n" + markdown
if links:
    body += "\n\n---\n" + " \u00b7 ".join(links)
body += "\n\n_Generated by [auto-arch-diagram](https://github.com/suryakumaran2611/auto-arch-diagram)._"

if len(body) > MAX_CHARS:
    body = body[:MAX_CHARS] + "\n\n_...truncated..._"

try:
    # Identify the token owner so we only update our own sticky notes.
    user_url = f"{api}/user"
    user_req = urllib.request.Request(user_url)
    user_req.add_header("PRIVATE-TOKEN", token)
    with urllib.request.urlopen(user_req, timeout=30) as response:
        token_user_id = json.loads(response.read().decode("utf-8")).get("id")

    notes = []
    page = 1
    while True:
        batch = request(
            "GET",
            f"/merge_requests/{mr_iid}/notes",
            params={"per_page": 100, "page": page, "sort": "desc", "order_by": "updated_at"},
        ) or []
        notes.extend(batch)
        if len(batch) < 100 or page >= 5:
            break
        page += 1

    existing = None
    for note in notes:
        author = note.get("author") or {}
        if MARKER in (note.get("body") or "") and author.get("id") == token_user_id:
            existing = note
            break

    if existing:
        request("PUT", f"/merge_requests/{mr_iid}/notes/{existing['id']}", {"body": body})
        print(f"[auto-arch-diagram] Updated merge request note {existing['id']}")
    else:
        created = request("POST", f"/merge_requests/{mr_iid}/notes", {"body": body})
        print(f"[auto-arch-diagram] Created merge request note {created.get('id')}")
except urllib.error.HTTPError as exc:
    detail = exc.read().decode("utf-8", errors="replace")[:500]
    warn(f"GitLab API returned HTTP {exc.code}: {detail}")
except urllib.error.URLError as exc:
    warn(f"Could not reach the GitLab API: {exc.reason}")
PY

log "Merge request comment step finished"
